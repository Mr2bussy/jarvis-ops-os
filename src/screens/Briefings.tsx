type Kind = 'morning' | 'market' | 'content' | 'custom';

export default function BriefingsScreen() {
  const [live, setLive] = useState<Briefing[]>(() => lsGet<Briefing[]>(LS.briefings, []));
  const [busy, setBusy] = useState<Kind | null>(null);
  const [error, setError] = useState('');
  const [extra, setExtra] = useState('');
  const [schedHour, setSchedHour] = useState<string>(() => localStorage.getItem('jarvis.briefing.hour') || '');
  const [schedKind, setSchedKind] = useState<Kind>('morning');
  const [schedEnabled, setSchedEnabled] = useState(() => localStorage.getItem('jarvis.briefing.enabled') === '1');
  const [schedStatus, setSchedStatus] = useState('');

  // Client-side scheduler: check every minute if it's time to auto-generate
  useEffect(() => {
    if (!schedEnabled || !schedHour) return;
    const tick = setInterval(async () => {
      const now = new Date();
      const [hh, mm] = schedHour.split(':').map(Number);
      if (now.getHours() === hh && now.getMinutes() === mm) {
        const lastRun = localStorage.getItem('jarvis.briefing.lastrun');
        const today = now.toDateString();
        if (lastRun === today) return; // already ran today
        localStorage.setItem('jarvis.briefing.lastrun', today);
        await gen(schedKind);
      }
    }, 60000);
    return () => clearInterval(tick);
  }, [schedEnabled, schedHour, schedKind]);

  function saveSchedule() {
    localStorage.setItem('jarvis.briefing.hour', schedHour);
    localStorage.setItem('jarvis.briefing.enabled', schedEnabled ? '1' : '0');
    setSchedStatus(schedEnabled && schedHour ? `Scheduled: ${schedKind} @ ${schedHour} daily` : 'Schedule cleared');
    setTimeout(() => setSchedStatus(''), 3000);
  }

  async function gen(kind: Kind) {
    setBusy(kind); setError('');
    try {
      const b = await composeBriefing(kind, extra);
      const next = [b, ...live].slice(0, 12);
      setLive(next);
      lsSet(LS.briefings, next);
    } catch (e: any) { setError(String(e?.message || e)); }
    setBusy(null);
  }

  function remove(id: string) {
    const next = live.filter(b => b.id !== id);
    setLive(next);
    lsSet(LS.briefings, next);
  }

  const KINDS: { id: Kind; label: string; color: string }[] = [
    { id: 'morning', label: 'Morning Intel', color: CYAN   },
    { id: 'market',  label: 'Market Brief',  color: AMBER  },
    { id: 'content', label: 'Content Brief', color: VIOLET },
    { id: 'custom',  label: 'Custom Topic',  color: JADE   },
  ];

  return (
    <div style={{ height: '100%', display: 'flex', flexDirection: 'column', gap: 12, minHeight: 0 }}>
      <ScreenHeader
        tag="BRIEFINGS"
        title="ON-DEMAND INTELLIGENCE"
        subtitle="Generate a live briefing in 3-8 seconds. Stored locally. Use Custom Topic for anything ad-hoc."
      />

      <TodaySnapshot />

      {/* ── Auto-Schedule Panel ────────────────────────────────────── */}
      <HoloPanel label="AUTO-SCHEDULE" code="SCHED" status={schedEnabled ? 'live' : 'idle'}>
        <div style={{ display: 'flex', gap: 12, alignItems: 'center', flexWrap: 'wrap' }}>
          <span className="hud-label" style={{ fontSize: 8, color: 'rgba(255,255,255,0.4)', letterSpacing: '0.18em' }}>DAILY TIME</span>
          <input type="time" value={schedHour} onChange={e => setSchedHour(e.target.value)}
            style={{ padding: '4px 8px', background: 'rgba(255,255,255,0.04)', border: '1px solid rgba(255,255,255,0.12)', color: 'rgba(255,255,255,0.75)', fontFamily: 'JetBrains Mono', fontSize: 11, outline: 'none' }} />
          <span className="hud-label" style={{ fontSize: 8, color: 'rgba(255,255,255,0.4)', letterSpacing: '0.18em' }}>TYPE</span>
          <div style={{ display: 'flex', gap: 4 }}>
            {(['morning','market','content','custom'] as Kind[]).map(k => (
              <button key={k} onClick={() => setSchedKind(k)} className="hud-label"
                style={{ padding: '3px 9px', fontSize: 8, cursor: 'pointer', letterSpacing: '0.1em',
                  border: `1px solid ${schedKind===k ? CYAN : 'rgba(255,255,255,0.1)'}`,
                  color: schedKind===k ? CYAN : 'rgba(255,255,255,0.35)',
                  background: schedKind===k ? 'rgba(0,229,255,0.08)' : 'transparent' }}>
                {k.toUpperCase()}
              </button>
            ))}
          </div>
          <button onClick={() => { setSchedEnabled(v => !v); }} className="hud-label"
            style={{ padding: '4px 10px', fontSize: 8, cursor: 'pointer', letterSpacing: '0.14em',
              border: `1px solid ${schedEnabled ? JADE : 'rgba(255,255,255,0.15)'}`,
              color: schedEnabled ? JADE : 'rgba(255,255,255,0.4)',
              background: schedEnabled ? 'rgba(0,208,132,0.08)' : 'transparent' }}>
            {schedEnabled ? '● ENABLED' : '○ DISABLED'}
          </button>
          <button onClick={saveSchedule} className="hud-label"
            style={{ padding: '4px 12px', fontSize: 8, cursor: 'pointer', letterSpacing: '0.14em', color: AMBER, border: `1px solid ${AMBER}55`, background: 'transparent' }}>
            SAVE
          </button>
          {schedStatus && <span className="font-mono" style={{ fontSize: 9, color: JADE, marginLeft: 4 }}>{schedStatus}</span>}
        </div>
      </HoloPanel>

      <HoloPanel label="COMPOSE NEW BRIEFING - LIVE" code="GEN" status="live">
        <div style={{ display: 'flex', gap: 12, alignItems: 'flex-start' }}>
          <div style={{ flex: 1 }}>
            <div className="hud-label" style={{ fontSize: 9, color: 'var(--cyan-dim)', letterSpacing: '0.32em', marginBottom: 6 }}>FOCUS / EXTRA CONTEXT (OPTIONAL)</div>
            <textarea
              value={extra}
              onChange={e => setExtra(e.target.value)}
              placeholder="e.g. 'Crypto + DAX, plus Berlin Startup News'"
              style={{ width: '100%', height: 60, background: 'oklch(0.06 0.014 240 / 0.6)', border: '1px solid var(--line)', color: 'var(--fg)', padding: 10, fontFamily: 'JetBrains Mono', fontSize: 11, lineHeight: 1.4, resize: 'none', outline: 'none' }}
            />
          </div>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 6, minWidth: 220 }}>
            {KINDS.map(k => (
              <button
                key={k.id}
                onClick={() => gen(k.id)}
                disabled={!!busy}
                className="hud-label"
                style={{
                  padding: '10px 12px', fontSize: 10, letterSpacing: '0.28em',
                  color: busy === k.id ? 'var(--cyan-dim)' : CYAN_BRIGHT,
                  border: `1px solid ${k.color}80`,
                  background: busy === k.id ? 'oklch(0.78 0.13 215 / 0.18)' : 'transparent',
                  cursor: busy ? 'wait' : 'pointer',
                  textShadow: busy ? 'none' : `0 0 6px ${k.color}`,
                  textAlign: 'left',
                  display: 'flex', justifyContent: 'space-between', alignItems: 'center', gap: 6,
                }}
              >
                <span>{k.label.toUpperCase()}</span>
                <span style={{ fontSize: 11 }}>{busy === k.id ? 'O' : '>'}</span>
              </button>
            ))}
          </div>
        </div>
        {error && <div className="font-mono" style={{ fontSize: 10, color: AMBER, marginTop: 8 }}>! {error}</div>}
      </HoloPanel>

      <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 12, flex: 1, minHeight: 0, overflow: 'auto' }} className="nx-scroll">
        {live.map(b => (
          <div key={b.id} style={{ position: 'relative' }}>
            <button
              onClick={() => remove(b.id)}
              className="hud-label"
              style={{ position: 'absolute', top: 8, right: 8, padding: '4px 8px', fontSize: 8.5, color: 'var(--cyan-dim)', border: '1px solid var(--line-soft)', letterSpacing: '0.22em', zIndex: 2 }}
            >X</button>
            <BriefingCard b={b} />
          </div>
        ))}

        {live.length === 0 && BRIEFINGS.length === 0 && (
          <div style={{ gridColumn: '1 / -1', display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', gap: 12, padding: 48, border: '1px dashed rgba(0,229,255,0.15)', background: 'rgba(0,229,255,0.02)' }}>
            <div className="hud-label" style={{ fontSize: 10, color: CYAN, letterSpacing: '0.4em' }}>NO BRIEFINGS YET</div>
            <div className="font-mono" style={{ fontSize: 11, color: 'var(--cyan-dim)', textAlign: 'center', maxWidth: 400, lineHeight: 1.6 }}>
              Click <strong style={{ color: CYAN_BRIGHT }}>Morning Intel</strong>, <strong style={{ color: AMBER }}>Market Brief</strong>,{' '}
              <strong style={{ color: VIOLET }}>Content Brief</strong>, or <strong style={{ color: JADE }}>Custom Topic</strong> above to generate your first live briefing with Claude AI.
            </div>
            <div className="font-mono" style={{ fontSize: 9, color: 'rgba(255,255,255,0.2)', letterSpacing: '0.2em' }}>BRIEFINGS ARE STORED IN LOCALSTORAGE - PERSIST ACROSS SESSIONS</div>
          </div>
        )}

        {live.length === 0 && BRIEFINGS.map(b => <BriefingCard key={b.id} b={b} />)}
      </div>
    </div>
  );
}