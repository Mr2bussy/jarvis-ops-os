/* -- Today Snapshot panel -- all real data -- */
function TodaySnapshot() {
  const runs   = lsGet<any[]>(LS.runs, []);
  const briefs = lsGet<any[]>(LS.briefings, []);
  const now    = new Date();
  const todayStr = now.toISOString().slice(0, 10);
  const timeStr  = now.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
  const dateStr  = now.toLocaleDateString([], { weekday: 'long', month: 'short', day: 'numeric' });

  const runsToday     = runs.filter((r: any) => r.at?.startsWith(todayStr)).length;
  const contentBriefs = briefs.filter((b: any) => b.tag?.toLowerCase().includes('content')).length;

  const [mt5Ok, setMt5Ok] = useState<boolean | null>(null);
  useEffect(() => {
    fetch('http://localhost:1234/api/v1/rates?symbol=BTCUSD&tf=M1&n=1', {
      signal: AbortSignal.timeout(2000),
    }).then(r => setMt5Ok(r.ok)).catch(() => setMt5Ok(false));
  }, []);

  const utcH = now.getUTCHours();
  const contentWindow =
    utcH >= 11 && utcH < 14 ? 'THREAD - PEAK WINDOW NOW'   :
    utcH >= 15 && utcH < 18 ? 'VIDEO - PRIME TIME WINDOW'  :
    utcH >= 18 && utcH < 21 ? 'REEL - EVENING WINDOW'      :
                               'STAND-BY - NEXT: 12:00 UTC';
  const cwActive = (utcH >= 11 && utcH < 14) || (utcH >= 15 && utcH < 18) || (utcH >= 18 && utcH < 21);

  const SNAPS = [
    { label: 'AI RUNS TODAY',    value: String(runsToday),     sub: `${runs.length} total stored`,        color: CYAN   },
    { label: 'CONTENT BRIEFS',   value: String(contentBriefs), sub: `${briefs.length} briefings total`,   color: VIOLET },
    { label: 'TOTAL AI RUNS',    value: String(runs.length),   sub: 'all sessions',                       color: JADE   },
    { label: 'BRIEFINGS STORED', value: String(briefs.length), sub: 'persisted locally',                  color: AMBER  },
    {
      label: 'TRADER BOT',
      value: mt5Ok === null ? '...' : mt5Ok ? 'LIVE' : 'OFFLINE',
      sub:   mt5Ok ? 'MT5 bridge :1234' : 'Start MT5 bridge',
      color: mt5Ok ? JADE : ROSE,
    },
    { label: 'CLAUDE API',       value: 'READY',               sub: 'Configure in Setup',                  color: CYAN  },
  ];

  const infoRows = [
    {
      label: 'CONTENT WINDOW',
      value: contentWindow,
      color: cwActive ? JADE : VIOLET,
      detail: 'Based on UTC peak-engagement hours: 11-14 (thread), 15-18 (video), 18-21 (reel)',
    },
    {
      label: 'TRADER BOT STATUS',
      value: mt5Ok === null ? 'CHECKING...' : mt5Ok ? 'MT5 BRIDGE ACTIVE' : 'MT5 NOT CONNECTED',
      color: mt5Ok ? JADE : ROSE,
      detail: mt5Ok
        ? 'Zeus hooks active - real-time order book + positions'
        : 'Launch MT5 + ZeusBot bridge on port 1234 to activate trading',
    },
    {
      label: 'AI SESSIONS',
      value: `${runs.length} TOTAL RUNS`,
      color: CYAN,
      detail: `${runsToday} runs today - ${runs.length} runs stored in localStorage`,
    },
    {
      label: 'BRIEFINGS',
      value: briefs.length > 0 ? `${briefs.length} STORED` : 'NONE YET',
      color: briefs.length > 0 ? JADE : AMBER,
      detail: briefs.length > 0
        ? 'Generated by Claude - persisted locally'
        : 'Tap Morning Intel, Market Brief, or Custom Topic',
    },
  ];

  return (
    <HoloPanel label={`TODAY'S INTEL SNAPSHOT - ${dateStr}`} code={timeStr} status="live" style={{ flexShrink: 0 }}>
      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(6, 1fr)', gap: 8, marginBottom: 12 }}>
        {SNAPS.map(s => (
          <div key={s.label} style={{ padding: '10px 10px', border: '1px solid var(--line-soft)', background: `${s.color}08`, borderTop: `2px solid ${s.color}` }}>
            <div className="hud-label" style={{ fontSize: 7.5, color: 'var(--cyan-dim)', letterSpacing: '0.18em', marginBottom: 4 }}>{s.label}</div>
            <div className="font-display" style={{ fontSize: 18, color: s.color, lineHeight: 1 }}>{s.value}</div>
            <div className="font-mono" style={{ fontSize: 8, color: 'var(--cyan-dim)', marginTop: 3 }}>{s.sub}</div>
          </div>
        ))}
      </div>
      <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 8 }}>
        {infoRows.map(item => (
          <div key={item.label} style={{ display: 'flex', gap: 10, padding: '10px 12px', border: `1px solid ${item.color}30`, background: `${item.color}06`, alignItems: 'center' }}>
            <div style={{ flex: 1 }}>
              <div className="hud-label" style={{ fontSize: 8, color: item.color, letterSpacing: '0.22em', marginBottom: 3 }}>{item.label}</div>
              <div className="font-mono" style={{ fontSize: 11, color: 'var(--fg)', lineHeight: 1.3 }}>{item.value}</div>
              <div className="font-mono" style={{ fontSize: 9, color: 'var(--cyan-dim)', marginTop: 2 }}>{item.detail}</div>
            </div>
            <div style={{ width: 6, height: 6, borderRadius: 99, background: item.color, flexShrink: 0, boxShadow: `0 0 8px ${item.color}` }} />
          </div>
        ))}
      </div>
    </HoloPanel>
  );
}

